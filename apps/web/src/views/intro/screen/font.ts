/**
 * The orientation's pixel font: one 7×11 grid per character, `#` for ink.
 *
 * Capitals and digits stand on rows 1–9, lowercase has a 6-row x-height, and rows 10–11 hold
 * descenders. Vertical strokes are two pixels wide and horizontal ones one, like the
 * Commodore 64's font, so text stays legible when the screen is shown small. Every character
 * advances 8 pixels: the glyph and a column of space.
 *
 * It is our own, drawn for this game, so there is no font to licence. Change a letter by
 * changing its pixels; a caption that needs a character missing here fails its test, rather
 * than rendering a gap on screen. There are no italics: emphasis is set in colour instead.
 */
